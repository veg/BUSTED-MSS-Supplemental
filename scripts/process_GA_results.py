"""
Author: Hannah Verdonk

Categories
True Positive (TP): neutral synonymous codons in the simulated data that were correctly identified by the GA
True Negative (TN): selected synonymous codons in the simulated data that were correctly identified by the GA
False Positive (FP): selected synonymous codons in the simulated data that were incorrectly marked neutral by the GA
False Negative (FN): neutral synonymous codons in the simulated data that were incorrectly marked selected by the GA
"""

import pandas as pd
import numpy as np
import os
import glob
import argparse

# create parser
parser = argparse.ArgumentParser()
 
# add arguments to the parser
parser.add_argument("--ref", help="File of neutral/selected codons used to simulate MSS data.")
parser.add_argument("--GA_result", help="GA results (as a tsv file) generated by HyPhy")
parser.add_argument("--codonGA", action='store_true', help="If the GA partitioned individual codons, use this flag.")
parser.add_argument("-o", "--outfile", help="what to name the results file")

# parse the arguments
args = parser.parse_args()

# suck in file used to define neutral set and extract true neutral codons from it
ref_path = args.ref
truth = pd.read_csv(ref_path, sep='\t')
neutral_ref = truth[truth.GROUP == 'NEUTRAL']
selected_ref = truth[truth.GROUP == 'SELECTED']

# suck in GA results file and report TP, FP, TN, FN, accuracy, precision, recall, F1, average support
inpt = pd.read_csv(args.GA_result, sep='\t')
neutral_label = inpt[inpt.GROUP == 'NEUTRAL']
selected_label = inpt[inpt.GROUP == 'SELECTED']
ambiguous_label = inpt[inpt.GROUP == 'AMBIGUOS']

if args.codonGA:
    TP = np.intersect1d(neutral_ref.CODON, neutral_label.CODON)
    TN = np.intersect1d(selected_ref.CODON, selected_label.CODON)
    FP = np.intersect1d(selected_ref.CODON, neutral_label.CODON)
    FN = np.intersect1d(neutral_ref.CODON, selected_label.CODON)
    # FP = np.setdiff1d(selected_ref.CODON, neutral_label.CODON)
    # FN = np.setdiff1d(neutral_ref.CODON, selected_label.CODON)
    ambig = list(ambiguous_label.CODON)

    assert (len(TP)+len(TN)+len(FP)+len(FN) != 0), "No overlap between amino acids in reference set and result set. Ensure that both sets name amino acids the same way (e.g., A for alanine, not ALA)"

    TP_mean_support = np.mean(inpt[inpt.CODON.isin(TP)].SUPPORT)
    TN_mean_support = np.mean(inpt[inpt.CODON.isin(TN)].SUPPORT)
    FP_mean_support = np.mean(inpt[inpt.CODON.isin(FP)].SUPPORT)
    FN_mean_support = np.mean(inpt[inpt.CODON.isin(FN)].SUPPORT)
    ambig_mean_support = np.mean(inpt[inpt.CODON.isin(ambiguous_label.CODON)].SUPPORT)

else:
    '''When the GA partitions codons by amino acid, all
    codons belonging to the same amino acid get assigned to the
    same rate class. Therefore, we want one result per amino acid.
    '''
    TP = np.intersect1d(neutral_ref.AminoAcid, neutral_label.AminoAcid)
    TN = np.intersect1d(selected_ref.AminoAcid, selected_label.AminoAcid)
    FP = np.intersect1d(selected_ref.AminoAcid, neutral_label.AminoAcid)
    FN = np.intersect1d(neutral_ref.AminoAcid, selected_label.AminoAcid)
    # FP = np.setdiff1d(selected_ref.AminoAcid, neutral_label.AminoAcid)
    # FN = np.setdiff1d(neutral_ref.AminoAcid, selected_label.AminoAcid)
    ambig = list(ambiguous_label.AminoAcid)

    assert (len(TP)+len(TN)+len(FP)+len(FN) != 0), "No overlap between amino acids in reference set and result set. Ensure that both sets name amino acids the same way (e.g., A for alanine, not ALA)"

    TP_mean_support = np.mean(inpt[inpt.AminoAcid.isin(TP)].SUPPORT)
    TN_mean_support = np.mean(inpt[inpt.AminoAcid.isin(TN)].SUPPORT)
    FP_mean_support = np.mean(inpt[inpt.AminoAcid.isin(FP)].SUPPORT)
    FN_mean_support = np.mean(inpt[inpt.AminoAcid.isin(FN)].SUPPORT)
    ambig_mean_support = np.mean(inpt[inpt.AminoAcid.isin(ambiguous_label.AminoAcid)].SUPPORT)

filename = args.GA_result.strip().split('/')[-1]

if len(TP)==0 and len(FP)==0:
    precision = 'INF'
else:
    precision = len(TP) / (len(TP)+len(FP))

if len(TP)==0 and len(FN) == 0:
    recall = 'INF'
else:
    recall = len(TP) / (len(TP)+len(FN))

if precision == 'INF' or recall == 'INF' or (precision + recall == 0):
    F1 = 'INF'
else:
    F1 = 2 * (recall*precision)/(recall+precision)


results = pd.DataFrame.from_dict({
                        "filename": filename,
			"TP": [len(TP)], 
                        "avg_TP_support": [TP_mean_support],
                        "TN": [len(TN)], 
                        "avg_TN_support": [TN_mean_support],
                        "FP": [len(FP)],
                        "avg_FP_support": [FP_mean_support],
                        "FN": [len(FN)],
                        "avg_FN_support": [FN_mean_support],
                        "accuracy": [(len(TP)+len(TN)) / (len(TP)+len(TN)+len(FP)+len(FN))],
                        "precision": [precision],
                        "recall": [recall],
                        "F1": [F1],
                        "ambiguous": [ambig],
                        "avg_ambiguous_support": [ambig_mean_support],
                        })
 

results.to_csv(args.outfile, index=False)


