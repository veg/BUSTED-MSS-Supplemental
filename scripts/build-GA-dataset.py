import argparse
import os
import random

# create parser
parser = argparse.ArgumentParser()
 
# add arguments to the parser
parser.add_argument("--msa", help="Source directory for gene alignments (which lack phylogenetic trees). Tree name must match alignment name")
parser.add_argument("--trees", help="Source directory for gene trees. Tree name must match alignment name")
# parser.add_argument("-n", "--subset", nargs='?', help="Optional. Only n randomly chosen files will be processed. If n > number of files in the directory, run this script on every file.")
parser.add_argument("-d", "--outdir", help="Destination directory for alignments generated by this script.")
# parser.add_argument('-o', '--outfile', help="Text file list of alignments generated by this script. Required by the GA")

# parse the arguments
args = parser.parse_args()

final_file_list = []
msa_path = args.msa
tree_path = args.trees
dest_path = args.outdir
# GA_filelist = args.outfile

tree_files = os.listdir(tree_path)
tree_files = [f for f in tree_files if os.path.isfile(tree_path+'/'+f)] #Filtering only the files.
tree_files = [f for f in tree_files if "bestTree" in f] # use the best tree

# select a random subset of files from the directory, if desired by the user
# if args.subset is not None:
#     if args.subset > len(tree_files):
#         pass
#     else:
#         tree_files = random.sample(tree_files, args.subset)

for f in tree_files:
    # filename = f[:-4]
    filename = f.replace(".msa.raxml.bestTree", "")
    alignmentfile = msa_path + "/" + filename + ".msa"
    treefile = tree_path + "/" + f 

    # if python can't find FILENAME.msa, it's probably because the msa has been filtered by BUSTED-E and renamed FILENAME.FILTER.msa
    # the filtering program appends the tree to the alignment automatically, so we can skip adding the raxml tree here
    if not os.path.isfile(alignmentfile):
        alignmentfile = alignmentfile[:-4] + ".FILTER.msa"
        symlinkfile = os.path.join(dest_path, filename + ".FILTER.msa") # symlink FILENAME.FILTER.msa to the new directory
        if not os.path.isfile(symlinkfile):
            # don't try to simlink if the file exists already (probably due to a half-done snakemake job)
            os.symlink(alignmentfile, symlinkfile)
    else: 
        # add raxml best tree to the bottom of each MSA (necessary for GA)
        with open(dest_path + "/" + filename + "_with_raxml_bestTree.msa", "w") as outfile:
            with open(alignmentfile, "r") as afile:
                outfile.write(afile.read())
            outfile.write("\n\n")
            with open(treefile, "r") as tfile:
                outfile.write(tfile.read())
